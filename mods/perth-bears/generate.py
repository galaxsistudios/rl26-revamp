def stock_careerdata():
    """{path: bytes} of the stock careerdata bundle (pack backup if installed)."""
    folder = os.path.join(STOCK, "careerdata")
    if os.path.isdir(folder):
        out = {}
        for dirpath, _d, names in os.walk(folder):
            for n in names:
                p = os.path.join(dirpath, n)
                out[os.path.relpath(p, folder).replace("\\", "/")] = open(p, "rb").read()
        return out
    raise SystemExit(f"no stock careerdata at {folder} - run "
                     f"python tools\\extract_m3mp.py --entry careerdata --out {folder} (on a stock install)")


def league_structure(raw):
    """Insert PERTH_ID into the NRL record's club list. The record holds its
    display name, then (u8 0, u32 count, count x u32 club id)."""
    name = raw.index(b"NRL\x00", raw.index(b"CompetitionMode_League_NRL_Title"))
    for q in range(name, name + 64):
        n = struct.unpack_from("<I", raw, q)[0]
        ids = [struct.unpack_from("<I", raw, q + 4 + 4 * i)[0] for i in range(n)] if 0 < n < 40 else []
        if ids == list(range(1, 18)):
            break
    else:
        raise SystemExit("career_leaguestructure: NRL club list (1..17) not found")
    out = bytearray(raw)
    struct.pack_into("<I", out, q, n + 1)
    end = q + 4 + 4 * n
    out[end:end] = struct.pack("<I", PERTH_ID)
    return bytes(out)


def clubs_domestic(raw, template=17):
    """Append a Perth record: 87 bytes, u32 club id, 32-byte name, then the
    club's career settings (a copy of the Dolphins')."""
    size = 87
    n = struct.unpack_from("<I", raw, 1)[0]
    if len(raw) != 5 + n * size:
        raise SystemExit("career_clubs_domestic: unexpected size")
    recs = [raw[5 + i * size:5 + (i + 1) * size] for i in range(n)]
    ids = [struct.unpack_from("<I", r, 0)[0] for r in recs]
    if PERTH_ID in ids:
        raise SystemExit("career_clubs_domestic already has club 220")
    rec = bytearray(recs[ids.index(template)])
    struct.pack_into("<I", rec, 0, PERTH_ID)
    rec[4:36] = b"Perth Bears".ljust(32, b"\x00")
    return raw[:1] + struct.pack("<I", n + 1) + raw[5:] + bytes(rec)


def read_draw(raw):
    ver, a, rounds = raw[0], *struct.unpack_from("<II", raw, 1)
    p, out = 9, []
    for _ in range(rounds):
        n = struct.unpack_from("<I", raw, p)[0]
        p += 4
        ms = [struct.unpack_from("<HHBHBBBB", raw, p + 11 * k) for k in range(n)]
        p += 11 * n
        out.append(ms)
    return (ver, a), out, raw[p:]


def write_draw(head, rounds, tail):
    out = bytearray([head[0]]) + struct.pack("<II", head[1], len(rounds))
    for ms in rounds:
        out += struct.pack("<I", len(ms))
        for m in ms:
            out += struct.pack("<HHBHBBBB", *m)
    return bytes(out + tail)


def nrl_draw(raw, teams=17):
    head, rounds, tail = read_draw(raw)
    perth = teams
    played = {t: 0 for t in range(teams)}
    home = True
    log = []
    for r, ms in enumerate(rounds):
        busy = {x for m in ms for x in m[:2]}
        byes = [t for t in range(teams) if t not in busy]
        if len(byes) >= 7:
            log.append(f"R{r + 1}: Perth bye")
            continue
        opp = min(byes, key=lambda t: (played[t], t))
        played[opp] += 1
        last = max(ms, key=lambda m: (m[3], m[4], m[5], m[6], m[7]))
        used = {(m[4], m[5], m[6], m[7]) for m in ms}
        hh, mi = next(t for t in ((16, 5), (14, 0), (18, 15), (20, 5), (15, 0)) if (last[4], last[5], *t) not in used)
        h, a = (perth, opp) if home else (opp, perth)
        ms.append((h, a, 2, last[3], last[4], last[5], hh, mi))
        log.append(f"R{r + 1}: {'v' if home else '@'} {opp} {last[3]}-{last[4]:02}-{last[5]:02} {hh:02}:{mi:02}")
        home = not home
    games = sum(1 for ms in rounds for m in ms if perth in m[:2])
    return write_draw(head, rounds, tail), games, log


def career():
    files = stock_careerdata()
    out = os.path.join(HERE, "career")
    os.makedirs(out, exist_ok=True)
    data = {
        "career_leaguestructure": league_structure(files["career/career_leaguestructure"]),
        "career_clubs_domestic": clubs_domestic(files["career/career_clubs_domestic"]),
    }
    draw, games, log = nrl_draw(files["career/career_nrl_fixture_season"])
    data["career_nrl_fixture_season"] = draw
    # round trip check: every other team still has its 24 games plus its Perth game(s)
    _h, rounds, _t = read_draw(draw)
    counts = {}
    for ms in rounds:
        for m in ms:
            for x in m[:2]:
                counts[x] = counts.get(x, 0) + 1
    for name, blob in data.items():
        with open(os.path.join(out, name), "wb") as f:
            f.write(blob)
    with open(os.path.join(HERE, "perth_draw.txt"), "w") as f:
        f.write("\n".join(log) + "\n")
    print(f"career: NRL list + {PERTH_ID}, clubs_domestic + Perth, draw: Perth {games} games; "
          f"games per team {sorted(set(counts.values()))}")


def main():
    club_record()
    career()


if __name__ == "__main__":
    main()
