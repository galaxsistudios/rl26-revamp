def load_movements():
    import importlib.util
    path = os.path.join(ROOT, "mods", "nrl-2027-player-movements", "generate.py")
    spec = importlib.util.spec_from_file_location("movements", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def club_record():
    mv = load_movements()
    world = mv.World()
    squad = json.load(open(os.path.join(HERE, "squad.json")))["roster"]
    stock_clubs = world.clubs
    t = stock_clubs[TEMPLATE]["tables"][0]
    bears = stock_clubs[KITS_FROM]["tables"][0]
    fields = dict(CLUB)
    fields["commentaryTeamMascotHash"] = bears["commentaryTeamMascotHash"]
    # no "Perth" commentary line exists: drop the location (Dolphins' would say "Dolphins"/Redcliffe)
    fields["commentaryTeamLocationHash"] = None
    fields["supporters"] = bears.get("supporters")
    for k in t:
        if k.startswith(("feederClubs", "fedFromClubs")):
            fields[k] = None
    lineups = mv.fix_lineups(world, TEMPLATE, squad)
    spec = {"_comment": "perth-bears (generated by generate.py)", "new": True, "cloneOf": TEMPLATE,
            "clubList": fields, "uniforms": {"from": KITS_FROM}, "rosterList": squad, "lineupTables": lineups}
    out = os.path.join(HERE, "defaultdata", "defaultdata_clubs")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, f"{PERTH_ID:06d}_Perth_Bears.json"), "w", encoding="utf-8") as f:
        json.dump(spec, f, indent=1)
    out = os.path.join(HERE, "defaultdata", "defaultdata_leagues")
    os.makedirs(out, exist_ok=True)
    for old in ("000001_NRL_2027_perth.json", "000018_NRL_2026_perth.json"):
        if os.path.exists(os.path.join(out, old)):
            os.remove(os.path.join(out, old))
    with open(os.path.join(out, f"{MAIN_NRL_LEAGUE:06d}_NRL_main_perth.json"), "w", encoding="utf-8") as f:
        json.dump({"_comment": "perth-bears: the visible NRL (Quick Match / competitions), 17 clubs + Perth",
                   "name": "NATIONAL RUGBY LEAGUE", "shortName": "NRL", "B": 1, "sortIndex": 1,
                   "clubs": NRL_2026 + [PERTH_ID]}, f, indent=1)
    with open(os.path.join(out, f"{CAREER_NRL_LEAGUE:06d}_NRL_2026_career.json"), "w", encoding="utf-8") as f:
        json.dump({"_comment": "perth-bears: hidden stock 17-club NRL that career / dynasty load",
                   "name": "NATIONAL RUGBY LEAGUE 2026", "shortName": "NRL 2026", "B": 0,
                   "sortIndex": CAREER_NRL_SORT, "clubs": NRL_2026}, f, indent=1)
    print(f"club {PERTH_ID}: {len(squad)} players; league {MAIN_NRL_LEAGUE} = NRL + {PERTH_ID}, "
          f"league {CAREER_NRL_LEAGUE} = hidden NRL 2026 (career)")


