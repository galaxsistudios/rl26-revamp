-- team-coaches: generated by mods/team-coaches/build_polos.py (palette.json).
-- Registers the coach polo design items. assetmap imports this file right after
-- assetmapitems and before the native asset map reads ItemMaps, the same window
-- rll4-legacy-kits uses from jigglyjointsconfig.lua.
do
	local ItemMaps = import("design.characters.assetmapitems").ItemMaps
	local map = ItemMaps.uniformTop
	local lookup = map.item_setup_lookup
	local colMap = ItemMaps.uniformTop_col

	local function addPolo(templateGuid, guid, colTexture)
		local template = lookup[templateGuid]

		if template == nil or lookup[guid] ~= nil then
			return
		end

		local item = {}

		for key, value in pairs(template) do
			item[key] = value
		end

		item.guid = guid
		item.colTexture = colTexture

		table.insert(map.item_setup, item)

		lookup[guid] = item

		if colMap.item_setup_lookup[colTexture] == nil then
			local entry = {
				name = colTexture,
				blend = colMap.blend
			}

			table.insert(colMap.item_setup, entry)

			colMap.item_setup_lookup[colTexture] = entry
		end
	end

	for _, polo in ipairs({
		{ 61001, 61101, "m_top_polo01_coach_black_col" }, -- black
		{ 61002, 61102, "m_top_polo01_coach_charcoal_col" }, -- charcoal
		{ 61003, 61103, "m_top_polo01_coach_silver_col" }, -- silver
		{ 61004, 61104, "m_top_polo01_coach_white_col" }, -- white
		{ 61005, 61105, "m_top_polo01_coach_navy_col" }, -- navy
		{ 61006, 61106, "m_top_polo01_coach_royal_col" }, -- royal
		{ 61007, 61107, "m_top_polo01_coach_sky_col" }, -- sky
		{ 61008, 61108, "m_top_polo01_coach_teal_col" }, -- teal
		{ 61009, 61109, "m_top_polo01_coach_green_col" }, -- green
		{ 61010, 61110, "m_top_polo01_coach_lime_col" }, -- lime
		{ 61011, 61111, "m_top_polo01_coach_yellow_col" }, -- yellow
		{ 61012, 61112, "m_top_polo01_coach_gold_col" }, -- gold
		{ 61013, 61113, "m_top_polo01_coach_orange_col" }, -- orange
		{ 61014, 61114, "m_top_polo01_coach_red_col" }, -- red
		{ 61015, 61115, "m_top_polo01_coach_maroon_col" }, -- maroon
		{ 61016, 61116, "m_top_polo01_coach_purple_col" }, -- purple
