-- Live 4 textures (generated by mods/rll4-legacy-kits/build_kits.py from
-- kits.json - edit those, not this block). assetmap imports this file right
-- after assetmapitems, so the items land before the native asset map reads
-- ItemMaps. Each item copies a stock template (same model) with a new guid
-- and colTexture, and is added to the guid lookup and the _col list that
-- assetmapitems builds before this runs.
do
	local ItemMaps = import("design.characters.assetmapitems").ItemMaps

	local function addItem(mapName, templateGuid, guid, colTexture, overrides)
		local map = ItemMaps[mapName]
		local lookup = map.item_setup_lookup
		local template = lookup[templateGuid]

		if template == nil or lookup[guid] ~= nil then
			return
		end

		local item = {}

		for key, value in pairs(template) do
			item[key] = value
		end

		item.guid = guid
		item.colTexture = colTexture

		for key, value in pairs(overrides or {}) do
			item[key] = value
		end

		table.insert(map.item_setup, item)

		lookup[guid] = item

		local colMap = ItemMaps[mapName .. "_col"]

		if colMap.item_setup_lookup[colTexture] == nil then
			local entry = {
				name = colTexture,
				blend = colMap.blend
			}

			table.insert(colMap.item_setup, entry)

			colMap.item_setup_lookup[colTexture] = entry
		end
	end

