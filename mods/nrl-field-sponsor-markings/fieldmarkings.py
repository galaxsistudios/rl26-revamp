#!/usr/bin/env python3
"""
fieldmarkings.py - build the grass sponsor markings from config/.

    config/positions.json   where markings can go (metres on the pitch)
    config/sponsors.json    reusable art (logo file, background, fit, ...)
    config/rounds/*.json    one per round: which field-markings values /
                            career events pick it, and what goes where

Every round becomes its own NEW model + texture bundle (appended with
add_entries.py), cloned from a stock sponsor model:

  - "full" rounds clone the stock Thursday model (fields/default/
    sponsor_field_thursdaynightfootball), which has every host:
        centre     nrlTelstraPremiership02  1 quad   1024x1024 texture
        squares_a  kiaTasman01 + 02         1 + 1    512x512 each
        squares_b  leagueStars01            2 quads  512x512 (shared)
        in_goal    wideLeft/Right_NRLFantasy (one flat rectangle per
                   in-goal, panels painted into 1024x256 textures)
    Hosts a round doesn't use are collapsed.
  - each "layer" position is one more model per round, cloned from the
    stock men's RLWC model (rlwc01 quad, 1024x1024), drawn on top.
  - rounds with "stock_model" just load that stock model (World Cups).

Quads are laid flat and axis-aligned over their position (models.py
place_quad), showing the whole texture. Clones get their own model name
(material paths) and texture names - same length, so nothing else in the
files moves - so no two rounds can share a material or texture through a
path-keyed cache. The stock sponsor entries stay as shipped.

stadiumgrass.lua (this mod) and enable-casual-fieldmarkings' Play Now list
carry tables generated from the round configs: run "lua" after editing
config/rounds/, then rebuild the scripts. "build" refuses to run while the
Lua is stale.

Usage (install with the game closed):
    python mods/nrl-field-sponsor-markings/fieldmarkings.py lua [--check]
    python mods/nrl-field-sponsor-markings/fieldmarkings.py build [--texconv PATH]
    python mods/nrl-field-sponsor-markings/fieldmarkings.py install [--confirm]

"build" writes _build/nrl-field-sponsor-markings/: the entries, plus
previews/<round>.png (top-down, main camera at the bottom) and
previews/all.png.
"""

