# ---- generated Lua ----------------------------------------------------------

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_map(name, pairs, indent):
    t = "\t" * indent
    if not pairs:
        return [f"{t}local {name} = {{}}"]
    lines = [f"{t}local {name} = {{"]
    for i, (k, v) in enumerate(pairs):
        lines.append(f"{t}\t{k} = {lua_str(v)}" + ("," if i < len(pairs) - 1 else ""))
    return lines + [f"{t}}}"]


def stadiumgrass_block(cfg):
    t = "\t"
    out = [f"{t}{LUA_BEGIN} from config/rounds/*.json - edit those, then run",
           f'{t}-- "python mods/nrl-field-sponsor-markings/fieldmarkings.py lua".',
           f"{t}local var_2_FieldRounds = {{"]
    rounds = cfg["rounds"]
    for i, r in enumerate(rounds):
        model = r["stock_model"] if "stock_model" in r else model_name(r)
        layers = [model_name(r, p) for p in layers_of(r)]
        out.append(f"{t}\t{r['id']} = {{")
        out.append(f"{t}\t\tmodel = {lua_str(model)},")
        if layers:
            out.append(f"{t}\t\tlayers = {{")
            out += [f"{t}\t\t\t{lua_str(n)}" + ("," if j < len(layers) - 1 else "") for j, n in enumerate(layers)]
            out.append(f"{t}\t\t}}")
        else:
            out.append(f"{t}\t\tlayers = {{}}")
        out.append(f"{t}\t}}" + ("," if i < len(rounds) - 1 else ""))
    out.append(f"{t}}}")
    for var, key in (("var_2_FieldBySpecialEvent", "special_events"), ("var_2_FieldByCompetition", "competitions"),
                     ("var_2_FieldByMarkings", "markings")):
        pairs, seen = [], {}
        for r in rounds:
            for name in r.get(key, []):
                if name in seen:
                    raise SystemExit(f"{key} {name} is claimed by rounds {seen[name]} and {r['id']}")
                seen[name] = r["id"]
                pairs.append((name, r["id"]))
        out += lua_map(var, pairs, 1)
    out.append(f"{t}{LUA_END}")
    return out


def menu_block(cfg):
    t = "\t\t"
    out = [f"{t}{LUA_BEGIN} from nrl-field-sponsor-markings/config/rounds/*.json (menu_label)"]
    for r in cfg["rounds"]:
        if r.get("menu_label") and r.get("markings"):
            out += [f"{t}{{", f"{t}\t{lua_str(r['markings'][0])},", f"{t}\t{lua_str(r['menu_label'])}", f"{t}}},"]
    out.append(f"{t}{LUA_END}")
    return out


def picker_block(cfg):
    """Rounds with a menu_label but no markings value: Play Now's round
    picker lists them (enable-casual-fieldmarkings)."""
    t = "	"
    out = [f"{t}{PICKER_BEGIN} (rounds with a menu_label and no markings)", f"{t}local var_17_Picker = {{"]
    rows = [r for r in cfg["rounds"] if r.get("menu_label") and not r.get("markings")]
    for i, r in enumerate(rows):
        out += [f"{t}	{{", f"{t}		round = {lua_str(r['id'])},", f"{t}		label = {lua_str(r['menu_label'])},",
                f"{t}		base = {lua_str(r.get('picker_base', PICKER_BASE))}", f"{t}	}}" + ("," if i < len(rows) - 1 else "")]
    return out + [f"{t}}}", f"{t}{PICKER_END}"]


def lua_targets(cfg):
    return [(STADIUMGRASS_LUA, stadiumgrass_block(cfg), LUA_BEGIN, LUA_END),
            (MENU_LUA, menu_block(cfg), LUA_BEGIN, LUA_END),
            (MENU_LUA, picker_block(cfg), PICKER_BEGIN, PICKER_END)]


def splice(path, block, begin=LUA_BEGIN, end=LUA_END):
    """(current text, text with the marked block replaced)."""
    with open(path, encoding="utf-8-sig", newline="") as f:
        text = f.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.split(nl)
    starts = [i for i, ln in enumerate(lines) if begin in ln]
    ends = [i for i, ln in enumerate(lines) if end in ln]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise SystemExit(f"{path}: expected one generated block")
    return text, nl.join(lines[:starts[0]] + block + lines[ends[0] + 1:])


def lua_stale(cfg):
    stale = []
    for path, block, begin, end in lua_targets(cfg):
        cur, new = splice(path, block, begin, end)
        if cur != new:
            stale.append(os.path.relpath(path, REPO_ROOT))
    return stale


def cmd_lua(args):
    cfg = load_config()
    if args.check:
        stale = lua_stale(cfg)
        print("stale: " + ", ".join(stale) if stale else "up to date")
        raise SystemExit(1 if stale else 0)
    for path, block, begin, end in lua_targets(cfg):
        cur, new = splice(path, block, begin, end)
        if cur != new:
            with open(path, "rb") as f:
                bom = f.read(3) == b"\xef\xbb\xbf"
            with open(path, "w", encoding="utf-8-sig" if bom else "utf-8", newline="") as f:
                f.write(new)
            print(f"  updated {os.path.relpath(path, REPO_ROOT)}")
        else:
            print(f"  {os.path.relpath(path, REPO_ROOT)} already up to date")


