# ---- config -----------------------------------------------------------------

def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def load_config():
    pos = load_json(os.path.join(CONFIG, "positions.json"))
    sponsors = {k: v for k, v in load_json(os.path.join(CONFIG, "sponsors.json")).items() if not k.startswith("_")}
    rounds = []
    rdir = os.path.join(CONFIG, "rounds")
    for fn in sorted(os.listdir(rdir)):
        if not fn.endswith(".json"):
            continue
        rid = fn[:-5]
        if not re.fullmatch(r"[a-z0-9]+", rid):
            raise SystemExit(f"rounds/{fn}: file names must be lowercase letters/digits")
        r = load_json(os.path.join(rdir, fn))
        r["id"] = rid
        rounds.append(r)
    cfg = {"stretch": pos["broadcast_stretch"], "positions": pos["positions"], "sponsors": sponsors,
           "rounds": rounds}
    for pname, p in cfg["positions"].items():
        if not re.fullmatch(r"[a-z0-9_]+", pname):
            raise SystemExit(f"position {pname!r}: names must be lowercase letters/digits/_")
        if p["host"] not in HOSTS and p["host"] != "layer":
            raise SystemExit(f"position {pname!r}: unknown host {p['host']!r}")
    built = [r for r in rounds if "stock_model" not in r]
    if len(built) > len(CODES):
        raise SystemExit(f"{len(built)} rounds but only {len(CODES)} texture codes")
    for code, r in zip(CODES, built):
        r["code"] = code
        r["plan"] = plan_round(cfg, r)
    return cfg


def plan_round(cfg, r):
    """[(position name, host, geometry, art spec)] for one round."""
    plan, hosts = [], set()
    for pname, value in r.get("slots", {}).items():
        if pname not in cfg["positions"]:
            raise SystemExit(f"rounds/{r['id']}.json: unknown position {pname!r}")
        pos = cfg["positions"][pname]
        spec = {"sponsor": value} if isinstance(value, str) else dict(value)
        if "sponsor" in spec:
            if spec["sponsor"] not in cfg["sponsors"]:
                raise SystemExit(f"rounds/{r['id']}.json: unknown sponsor {spec['sponsor']!r}")
            spec = {**cfg["sponsors"][spec["sponsor"]], **{k: v for k, v in spec.items() if k != "sponsor"}}
        geom = {k: v for k, v in pos.items() if k != "host"}
        for k in list(spec):
            if k in geom:
                geom[k] = spec.pop(k)
        if "art" not in spec:
            raise SystemExit(f"rounds/{r['id']}.json: {pname} has no art")
        host = pos["host"]
        if host != "layer":
            if host in hosts:
                raise SystemExit(f"rounds/{r['id']}.json: two positions use host {host}")
            hosts.add(host)
        plan.append((pname, host, geom, spec))
    return plan


def model_name(r, layer=None):
    return f"sponsor_field_rv_{r['id']}" + (f"_{layer}" if layer else "")


def layers_of(r):
    return [pname for pname, host, _g, _s in r.get("plan", []) if host == "layer"]


def rect_of(geom, side=1):
    """(x0, x1, z0, z1) on a normal (not _flipped) model."""
    cx, cz = side * geom["x"], geom["z"]
    return (cx - geom["along"] / 2, cx + geom["along"] / 2, cz - geom["across"] / 2, cz + geom["across"] / 2)


def stored(rect, flipped):
    """A rect in a model's own coordinates: _flipped models are turned 180."""
    x0, x1, z0, z1 = rect
    return (-x1, -x0, -z1, -z0) if flipped else rect


# ---- stock blobs ------------------------------------------------------------

def stock_blob(entry):
    """(stored bytes, sizes) of the SHIPPED entry: pack.py's backup if
    something replaced it in place, else the live blob."""
    meta_path = pack.backup_meta_path(entry)
    if os.path.exists(meta_path):
        meta = load_json(meta_path)
        sizes = tuple(meta[k] for k in ("main_compressed_size", "main_uncompressed_size",
                                         "vram_compressed_size", "vram_uncompressed_size"))
        return open(meta["blob_backup"], "rb").read(), sizes
    *_, bpath = ce.read_blob_full(pack.BLOBSET_PATH, entry)
    return open(bpath, "rb").read(), pack.entry_sizes(ce._INDEX_DATA, ce._SIZE_TABLE_OFF, entry)


def stock_model(name, flipped):
    stored_bytes, sizes = stock_blob(entries.legacy(STOCK[name] + (2 if flipped else 0)))
    if sizes[0] != len(stored_bytes) or sizes[2] != 0:
        raise RuntimeError(f"stock model {name} has unexpected sizes {sizes}")
    return models.Model(models.decode(stored_bytes))


def stock_txpk(name, flipped):
    """(header, payload) of a stock sponsor bundle. Written back as main raw
    + vram chunk-framed, the layout the shipped bundles use."""
    stored_bytes, (main_c, main_u, vram_c, vram_u) = stock_blob(entries.legacy(STOCK[name] + (3 if flipped else 1)))
    if vram_u == 0:
        raise RuntimeError(f"{name} bundle has no vram component")
    if main_c == main_u and vram_c == vram_u:
        raw = stored_bytes
    elif main_c == main_u or vram_c == vram_u:
        raw = stored_bytes[:main_u] + ce.decode_outer_zstd_frames(stored_bytes[main_u:])
    else:
        raw = ce.decode_outer_zstd_frames(stored_bytes)
    header, payload = raw[:main_u], raw[main_u:]
    if struct.unpack_from("<I", header, 0)[0] != et.TXPK_MAGIC or len(payload) != vram_u:
        raise RuntimeError(f"{name} bundle did not decode as a TXPK")
    return header, bytearray(payload)


def member_table(header):
    """[(member path without .dds, data_off, data_size)] in header order."""
    count = struct.unpack_from("<I", header, 4)[0]
    out = []
    for i in range(count):
        path_off, _size, data_off, data_size = struct.unpack_from("<4I", header, 8 + i * 16)
        end = header.index(b"\x00", path_off + 20)
        out.append((header[path_off + 20:end].decode("latin1").replace("\\", "/"), data_off, data_size))
    return out


def dds_upright(dds):
    return Image.open(io.BytesIO(dds)).convert("RGBA").transpose(Image.FLIP_TOP_BOTTOM)


_stock_art = {}


def stock_art(ref):
    """'<model>/<texture>' -> the shipped texture, upright."""
    if ref not in _stock_art:
        model, tex = ref.split("/")
        header, payload = stock_txpk(model, False)
        table = {p: (o, s) for p, o, s in member_table(header)}
        key = f"{SPONSOR_DIR}sponsor_field_{tex}_col"
        if key not in table:
            raise SystemExit(f"stock:{ref}: {model}'s bundle has no {tex}")
        o, s = table[key]
        _stock_art[ref] = dds_upright(bytes(payload[o:o + s]))
    return _stock_art[ref]


# ---- art --------------------------------------------------------------------

def load_spec_art(spec):
    if spec["art"].startswith("stock:"):
        im = art.crop_alpha(stock_art(spec["art"][6:]))
    else:
        im = art.crop_alpha(art.load_art(spec["art"]))
    if "mark" in spec:
        im = art.white_mark_from_background(im, *spec["mark"])
    if spec.get("white"):
        im = art.whiten(im)
    if spec.get("invert"):
        im = art.invert_cutout(im)
    if "text" in spec:
        im = art.with_caption(im, spec["text"], os.path.join(REPO_ROOT, spec.get("font", "Maison-Neue-Extended-Bold.ttf")),
                              spec.get("text_colour", (255, 255, 255)))
    return im


def compose(spec, size, along, across):
    """The upright texture for a slot `size` pixels big that covers along x
    across metres on the pitch (across already divided by the broadcast
    stretch where that applies): art laid out at its true look, then
    resampled into the texture's own aspect."""
    scale = 2048 / max(along, across)
    cw, ch = max(1, round(along * scale)), max(1, round(across * scale))
    bg = tuple(spec["background"]) + (255,) if "background" in spec else (255, 255, 255, 0)
    canvas = Image.new("RGBA", (cw, ch), bg)
    if spec["art"] == "none":
        return canvas.resize(size, Image.LANCZOS)
    im = load_spec_art(spec)
    m = round(spec.get("margin", 0) * min(cw, ch))
    box = (m, m, cw - m, ch - m)
    fit = spec.get("fit", "contain")
    if fit == "contain":
        art.fit_into(canvas, im, box)
    elif fit in ("stretch", "cover"):
        bw, bh = box[2] - box[0], box[3] - box[1]
        if fit == "cover":
            s = max(bw / im.width, bh / im.height)
            cw2, ch2 = round(bw / s), round(bh / s)
            left, top = (im.width - cw2) // 2, (im.height - ch2) // 2
            im = im.crop((left, top, left + cw2, top + ch2))
        canvas.alpha_composite(im.convert("RGBa").resize((bw, bh), Image.LANCZOS).convert("RGBA"), box[:2])
    else:
        raise SystemExit(f"unknown fit {fit!r}")
    return canvas.convert("RGBa").resize(size, Image.LANCZOS).convert("RGBA")


def compose_in_goal(spec, size, geom, sign):
    """In-goal texture (models.in_goal_uv layout: u across the field, v from
    the try line to the dead-ball line, upright pixel = (u*w, (1-v)*h)):
    transparent, with one flat panel per geom["panels_z"]. Panels read left
    to right for someone on the field facing the in-goal, top towards the
    dead-ball line; in_goal_uv's abs() mirrors the -x end, so its art is
    mirrored to match."""
    w, h = size
    out = Image.new("RGBA", size, (255, 255, 255, 0))
    length, depth = geom["length"], geom["depth"]
    panel = compose(spec, (round(length * 100), round(depth * 100)), length, depth)
    if sign < 0:
        panel = panel.transpose(Image.FLIP_LEFT_RIGHT)
    mid = sum(IN_GOAL_X) / 2
    for zc in geom["panels_z"]:
        u0, v_top = models.in_goal_uv(sign * (mid + depth / 2), zc - length / 2, IN_GOAL_X, IN_GOAL_Z)
        u1, v_bot = models.in_goal_uv(sign * (mid - depth / 2), zc + length / 2, IN_GOAL_X, IN_GOAL_Z)
        box = (round(u0 * w), round((1 - v_top) * h), round(u1 * w), round((1 - v_bot) * h))
        out.alpha_composite(panel.convert("RGBa").resize((box[2] - box[0], box[3] - box[1]), Image.LANCZOS)
                            .convert("RGBA"), box[:2])
    return out


# ---- models + bundles -------------------------------------------------------

def tex_rename(r, tex, layer_index=None):
    if layer_index is not None:
        return f"rlwc{r['code']}{layer_index + 1}"
    return tex[:-2] + r["code"] + tex[-1]


def internal_name(r, base, layer_index=None):
    tag = f"rv{r['code']}" + (str(layer_index + 1) if layer_index is not None else r["id"])
    return (tag + "x" * len(base))[:len(base)]


def build_full_model(r, flipped):
    """The round's main model. Returns (model bytes, slots): slots =
    [(texture, kind, geom, spec, extra)] to paint, where extra is the end
    (+1/-1) of an in_goal texture, or the sides of halfway (1 / -1) a quad
    texture is drawn on."""
    m = stock_model(FULL_BASE, flipped)
    used = {host: (pname, geom, spec) for pname, host, geom, spec in r["plan"] if host != "layer"}
    slots = []
    for host, parts in HOSTS.items():
        if host not in used:
            for mat, _tex in parts:
                m.collapse(mat)
            continue
        pname, geom, spec = used[host]
        if host == "in_goal":
            for mat, tex in parts:
                sign = m.in_goal_rect(mat, IN_GOAL_X, IN_GOAL_Z)
                # "ends": per-end overrides, keyed by the end on a normal
                # model ("neg" = -x, "pos" = +x); _flipped is turned 180.
                end = "pos" if (sign > 0) != flipped else "neg"
                end_spec = {k: v for k, v in spec.items() if k != "ends"}
                end_spec.update(spec.get("ends", {}).get(end, {}))
                slots.append((tex, "in_goal", geom, end_spec, sign))
            continue
        sides = (1,) if host == "centre" else (1, -1)
        rects = [stored(rect_of(geom, s), flipped) for s in sides]
        for mat, tex in parts:
            for q in range(m.quad_count(mat)):
                cx = m.quad_centre_x(mat, q)
                rect = rects[0] if len(rects) == 1 else min(rects, key=lambda rc: abs((rc[0] + rc[1]) / 2 - cx))
                m.place_quad(mat, q, rect, flipped)
            if tex not in [s[0] for s in slots]:
                slots.append((tex, "quad", geom, spec, sides))
    for _host, parts in HOSTS.items():
        for _mat, tex in parts:
            m.rename_texture(f"sponsor_field_{tex}_col", f"sponsor_field_{tex_rename(r, tex)}_col")
    m.swap_model_name(FULL_BASE, internal_name(r, FULL_BASE))
    return m.bytes(), slots


def build_layer_model(r, k, geom, flipped):
    m = stock_model(LAYER_BASE, flipped)
    mat, tex = LAYER_HOST
    m.place_quad(mat, 0, stored(rect_of(geom), flipped), flipped)
    for c in LAYER_COLLAPSE:
        m.collapse(c)
    m.rename_texture(f"sponsor_field_{tex}_col", f"sponsor_field_{tex_rename(r, tex, k)}_col")
    m.swap_model_name(LAYER_BASE, internal_name(r, LAYER_BASE, k))
    return m.bytes()


class Encoder:
    """BC7-encodes slot images, caching identical ones (normal and _flipped
    bundles share most art, and so do rounds)."""

    def __init__(self, texconv, tmp):
        self.texconv, self.tmp, self.cache = texconv, tmp, {}

    def encode(self, orig, upright):
        key = hashlib.sha1(orig[:148] + upright.tobytes()).hexdigest()
        if key not in self.cache:
            self.cache[key] = art.encode_like(orig, upright, self.texconv, self.tmp)
        return self.cache[key]


def build_bundle(cfg, base, flipped, slots, renames, enc, previews):
    """Paint `slots` into a copy of a stock bundle and rename its members.
    previews collects (texture, kind, geom, upright, extra)."""
    header, payload = stock_txpk(base, flipped)
    table = {p: (o, s) for p, o, s in member_table(header)}
    for tex, kind, geom, spec, extra in slots:
        o, s = table[f"{SPONSOR_DIR}sponsor_field_{tex}_col"]
        orig = bytes(payload[o:o + s])
        w, h = int.from_bytes(orig[16:20], "little"), int.from_bytes(orig[12:16], "little")
        if spec["art"] == "stock":
            upright = dds_upright(orig)
        else:
            if kind == "in_goal":
                upright = compose_in_goal(spec, (w, h), geom, extra)
            else:
                upright = compose(spec, (w, h), geom["along"], geom["across"] / cfg["stretch"])
            payload[o:o + s] = enc.encode(orig, upright)
        previews.append((tex, kind, geom, upright, extra))
    before = [p for p, _o, _s in member_table(header)]
    for old, new in renames.items():
        old_b, new_b = f"/sponsor_field_{old}_col\x00".encode(), f"/sponsor_field_{new}_col\x00".encode()
        if header.count(old_b) != 1:
            raise RuntimeError(f"{base} bundle: expected one member named {old}")
        header = header.replace(old_b, new_b)
    after = [p for p, _o, _s in member_table(header)]
    if before == sorted(before) and after != sorted(after):
        raise RuntimeError(f"{base} bundle: renames broke the member order ({after})")
    vram = texture_mods.encode_outer_chunks(bytes(payload))
    return header + vram, (len(header), len(header), len(vram), len(payload))


# ---- previews ---------------------------------------------------------------

PPM = 10  # preview pixels per metre
PREVIEW_X, PREVIEW_Z = 61, 37


def to_px(x, z):
    return round((x + PREVIEW_X) * PPM), round((z + PREVIEW_Z) * PPM)


def preview_round(r, items):
    """Top-down pitch, main camera at the bottom (+z), as the art lands."""
    img = Image.new("RGBA", to_px(PREVIEW_X, PREVIEW_Z), (52, 112, 52, 255))
    d = ImageDraw.Draw(img)
    for x in (-58, -50, -40, -30, -20, -10, 0, 10, 20, 30, 40, 50, 58):
        d.line([to_px(x, -34), to_px(x, 34)], fill=(235, 235, 235, 255), width=2)
    for z in (-34, 34):
        d.line([to_px(-58, z), to_px(58, z)], fill=(235, 235, 235, 255), width=2)
    for x in (-40, -30, -20, -10, 10, 20, 30, 40):
        for z in (-24, 24):
            d.text(to_px(x - 1.2, z - 0.8), str(50 - abs(x)), fill=(235, 235, 235, 255))
    for tex, kind, geom, upright, sign in items:
        if kind == "in_goal":
            x0, x1 = sorted((sign * IN_GOAL_X[0], sign * IN_GOAL_X[1]))
            (px0, pz0), (px1, pz1) = to_px(x0, -IN_GOAL_Z), to_px(x1, IN_GOAL_Z)
            xs = np.linspace(x0, x1, px1 - px0)
            zs = np.linspace(-IN_GOAL_Z, IN_GOAL_Z, pz1 - pz0)
            src = np.array(upright)
            h, w = src.shape[:2]
            u, v = models.in_goal_uv(xs[None, :], zs[:, None], IN_GOAL_X, IN_GOAL_Z)
            cols = np.clip((u * w).astype(int), 0, w - 1)
            rows = np.clip(((1 - v) * h).astype(int), 0, h - 1)
            img.alpha_composite(Image.fromarray(src[rows, cols]), (px0, pz0))
            continue
        for s in sign:  # for quads: the sides of halfway it is drawn on
            x0, x1, z0, z1 = rect_of(geom, s)
            (px0, pz0), (px1, pz1) = to_px(x0, z0), to_px(x1, z1)
            img.alpha_composite(upright.resize((px1 - px0, pz1 - pz0), Image.LANCZOS), (px0, pz0))
    d.text((8, 6), f"{r['label']}  (rounds/{r['id']}.json)  - main camera at the bottom", fill=(255, 255, 0, 255))
    return img


