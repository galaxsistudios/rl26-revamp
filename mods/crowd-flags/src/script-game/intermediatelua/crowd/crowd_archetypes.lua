-- Per match (called by crowd-team-kits' crowd_item_config, which reruns every
-- load; this module stays imported): every variant the crowd can pick gets a
-- 16-slot cols list (the native cols capacity). A fan's side picks the variant
-- for all their items, and the jerseys follow it, so home-side fans only wave
-- the home flag and away-side fans the away flag (a mixed list put Rabbitohs
-- flags in Roosters fans' hands). Neutral fans, in generic gear, get an even mix.
local CROWD_FLAGS_SLOTS = 16
local CROWD_FLAGS_HOME_SHARE = { home = 16, away = 0, neutral = 8 }

local function crowdFlagsMix(homeFlags, awayFlags, homeSlots)
	local cols, placed, homeNext, awayNext = {}, 0, 0, 0

	-- spread the home slots evenly through the list; each side cycles
	-- through its club's flag designs so fans in a stand vary
	for slot = 1, CROWD_FLAGS_SLOTS do
		if math.floor(slot * homeSlots / CROWD_FLAGS_SLOTS) > placed then
			placed = placed + 1
			homeNext = homeNext % #homeFlags + 1

			table.insert(cols, homeFlags[homeNext])
		else
			awayNext = awayNext % #awayFlags + 1

			table.insert(cols, awayFlags[awayNext])
		end
	end

	return cols
end

rawset(_G, "crowdFlagsPerMatch", function(items, teams, log)
	if type(teams) ~= "table" or not items.prop_flagSmall then
		return
	end

	local fallback = { "crowd_flag_default01_col" }
	local homeTex = crowdFlagsTeams[teams.home] or fallback
	local awayTex = crowdFlagsTeams[teams.away] or fallback
	local neutral = crowdFlagsMix(homeTex, awayTex, CROWD_FLAGS_HOME_SHARE.neutral)
	local variants = {
		base = {
			cols = neutral,
			nrms = crowdFlagsVariants.base.nrms,
			mats = crowdFlagsVariants.base.mats
		},
		homeDefault = {
			cols = crowdFlagsMix(homeTex, awayTex, CROWD_FLAGS_HOME_SHARE.home)
		},
		awayDefault = {
			cols = crowdFlagsMix(homeTex, awayTex, CROWD_FLAGS_HOME_SHARE.away)
		}
	}

	variants["teamID" .. tostring(teams.home)] = { cols = variants.homeDefault.cols }
	variants["teamID" .. tostring(teams.away)] = { cols = variants.awayDefault.cols }

	if teams.home == teams.away then
		variants["teamID" .. tostring(teams.home)] = { cols = neutral }
	end

	items.prop_flagSmall.variants = variants

	if log then
		log("crowd-flags: home %s (%d designs: %s), away %s (%d designs: %s)", tostring(teams.home), #homeTex, table.concat(homeTex, " "), tostring(teams.away), #awayTex, table.concat(awayTex, " "))
	end
end)

